pub fn holiday_name(d: NaiveDate) -> Option<&'static str> {
    let key = (d.year(), d.month(), d.day());
    HOLIDAYS.binary_search_by(|(k, _)| k.cmp(&key)).ok().map(|i| HOLIDAYS[i].1)
}

#[cfg(test)]
mod tests {
    use super::*;
    use chrono::NaiveDate;

    #[test]
    fn holiday_known_dates() {
        let d = |y, m, day| NaiveDate::from_ymd_opt(y, m, day).unwrap();
        assert_eq!(holiday_name(d(2026, 11, 3)), Some("文化の日"));
        assert_eq!(holiday_name(d(2026, 11, 12)), None);
        assert_eq!(holiday_name(d(2027, 1, 1)), Some("元日"));
    }
}
